"""
═══════════════════════════════════════════════════════════════
ARIA IK Benchmark Node
Comprehensive comparison of all IK solvers.
200 randomly sampled reachable target poses, reproducible.
Auto-selects best solver and saves to config.
═══════════════════════════════════════════════════════════════
"""
import math
import os
import time
from typing import Dict, List

import numpy as np
import yaml

import rclpy
from rclpy.node import Node
from std_srvs.srv import Trigger

from arm_ik.ik_solvers.aria_analytical_ik import (
    IKResult, SolverConfig, JOINT_LIMITS, forward_kinematics,
    solve_analytical, solve_from_pose_stamped,
    _rotation_matrix_to_quaternion,
)
from arm_ik.ik_solvers.ikpy_solver import solve_ikpy, IKPY_AVAILABLE
from arm_ik.ik_solvers.robotics_toolbox_solver import solve_rtb, RTB_AVAILABLE
from arm_ik.ik_solvers.neural_ik_solver import solve_neural, TORCH_AVAILABLE


# ═══════════════════════════════════════════════════════════════
# Benchmark Pose Generation
# ═══════════════════════════════════════════════════════════════
def generate_benchmark_poses(n_poses: int = 200,
                             seed: int = 12345) -> List[Dict]:
    """
    Generate N reachable target poses by:
      1. Sample random valid joint configs
      2. Compute FK → get end-effector pose
      3. Store pose + ground-truth joints

    All poses are guaranteed reachable (generated by FK).

    Args:
        n_poses: number of test poses
        seed: random seed for reproducibility

    Returns:
        List of dicts with 'position', 'orientation', 'joints'
    """
    rng = np.random.default_rng(seed)
    poses = []

    for _ in range(n_poses):
        # Random valid joint configuration
        q = np.array([
            rng.uniform(JOINT_LIMITS[j, 0] * 0.9, JOINT_LIMITS[j, 1] * 0.9)
            for j in range(5)
        ])

        # Compute FK
        T = forward_kinematics(q)
        pos = T[:3, 3].tolist()
        quat = _rotation_matrix_to_quaternion(T[:3, :3]).tolist()

        poses.append({
            'position': pos,
            'orientation': quat,
            'ground_truth_joints': q.tolist(),
        })

    return poses


def save_benchmark_poses(poses: List[Dict], path: str):
    """Save benchmark poses to YAML file."""
    data = {
        'n_poses': len(poses),
        'seed': 12345,
        'description': 'Benchmark poses for ARIA IK solver comparison',
        'poses': poses,
    }
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        yaml.dump(data, f, default_flow_style=False)


def load_benchmark_poses(path: str) -> List[Dict]:
    """Load benchmark poses from YAML file."""
    with open(path, 'r') as f:
        data = yaml.safe_load(f)
    return data['poses']


# ═══════════════════════════════════════════════════════════════
# Solver Registry
# ═══════════════════════════════════════════════════════════════
def _run_solver(solver_name: str,
                target_pos: np.ndarray,
                target_orient: np.ndarray,
                current_joints: np.ndarray,
                config: SolverConfig) -> IKResult:
    """Run a specific solver by name."""
    if solver_name == 'analytical':
        return solve_from_pose_stamped(target_pos, target_orient, config)
    elif solver_name == 'ikpy':
        return solve_ikpy(target_pos, config=config)
    elif solver_name == 'rtb_LM':
        return solve_rtb(target_pos, method='LM', config=config)
    elif solver_name == 'rtb_GN':
        return solve_rtb(target_pos, method='GN', config=config)
    elif solver_name == 'neural':
        return solve_neural(target_pos, target_orient)
    else:
        return IKResult(success=False, message=f"Unknown solver: {solver_name}")


# ═══════════════════════════════════════════════════════════════
# Benchmark Runner
# ═══════════════════════════════════════════════════════════════
def run_benchmark(poses: List[Dict]) -> Dict:
    """
    Run all solvers against all benchmark poses.

    Returns:
        Dict of solver_name → metrics dict
    """
    solvers = ['analytical']
    if IKPY_AVAILABLE:
        solvers.append('ikpy')
    if RTB_AVAILABLE:
        solvers.extend(['rtb_LM', 'rtb_GN'])
    if TORCH_AVAILABLE:
        solvers.append('neural')

    print(f"\nAvailable solvers: {solvers}")
    print(f"Running benchmark on {len(poses)} poses...\n")

    results = {}

    for solver_name in solvers:
        solve_times = []
        position_errors = []
        successes = 0
        joint_travels = []

        for i, pose_data in enumerate(poses):
            target_pos = np.array(pose_data['position'])
            target_orient = np.array(pose_data['orientation'])
            gt_joints = np.array(pose_data['ground_truth_joints'])

            config = SolverConfig(
                current_joints=gt_joints + np.random.randn(5) * 0.1,
                tolerance_m=0.005,
            )

            result = _run_solver(
                solver_name, target_pos, target_orient,
                gt_joints, config
            )

            solve_times.append(result.solve_time_ms)

            if result.success:
                successes += 1
                position_errors.append(result.position_error_m * 1000)  # mm
                travel = np.sum(np.abs(result.joint_angles - gt_joints))
                joint_travels.append(travel)
            else:
                position_errors.append(float('nan'))

        # Compute metrics
        valid_errors = [e for e in position_errors if not math.isnan(e)]

        metrics = {
            'success_rate_pct': 100.0 * successes / len(poses),
            'mean_solve_time_ms': np.mean(solve_times),
            'p95_solve_time_ms': np.percentile(solve_times, 95),
            'mean_position_error_mm': np.mean(valid_errors) if valid_errors else float('inf'),
            'max_position_error_mm': max(valid_errors) if valid_errors else float('inf'),
            'mean_joint_travel_rad': np.mean(joint_travels) if joint_travels else float('inf'),
            'n_success': successes,
            'n_total': len(poses),
        }
        results[solver_name] = metrics

    return results


def print_benchmark_results(results: Dict) -> str:
    """Print formatted benchmark comparison table."""
    header = (
        "══════════════════════════════════════════════════════════════\n"
        " ARIA IK Solver Benchmark Results\n"
        "══════════════════════════════════════════════════════════════\n"
        f" {'Solver':<20s} | {'Success%':>8s} | {'Mean ms':>8s} | "
        f"{'P95 ms':>8s} | {'Error mm':>8s}\n"
        "──────────────────────────────────────────────────────────────"
    )
    print(header)

    rows = []
    for solver_name, metrics in results.items():
        row = (
            f" {solver_name:<20s} | "
            f"{metrics['success_rate_pct']:7.1f}% | "
            f"{metrics['mean_solve_time_ms']:7.2f} | "
            f"{metrics['p95_solve_time_ms']:7.2f} | "
            f"{metrics['mean_position_error_mm']:7.2f}"
        )
        print(row)
        rows.append(row)

    print("══════════════════════════════════════════════════════════════")

    return header + '\n' + '\n'.join(rows)


def select_best_solver(results: Dict) -> tuple:
    """
    Auto-select the best solver based on:
      1. Success rate (must be > 90%)
      2. Position accuracy (lower is better)
      3. Speed (faster is better, tiebreaker)

    Returns:
        (primary_solver_name, fallback_solver_name)
    """
    # Score each solver: success_rate * accuracy_score * speed_score
    scored = {}
    for name, m in results.items():
        if m['success_rate_pct'] < 50:
            scored[name] = 0
            continue

        # Higher success → higher score
        sr = m['success_rate_pct'] / 100.0

        # Lower error → higher score (invert, cap at 10mm)
        err = max(m['mean_position_error_mm'], 0.01)
        acc = min(10.0 / err, 10.0)

        # Faster → higher score (invert, cap at 100ms)
        spd = min(100.0 / max(m['mean_solve_time_ms'], 0.001), 100.0)

        # Weighted composite: accuracy most important, then success, then speed
        scored[name] = sr * 40 + acc * 40 + spd * 20

    if not scored:
        return 'analytical', 'analytical'

    ranked = sorted(scored.items(), key=lambda x: -x[1])
    primary = ranked[0][0]
    fallback = ranked[1][0] if len(ranked) > 1 else primary

    print(f"\nSELECTED: {primary}")
    print(f"FALLBACK: {fallback}")

    return primary, fallback


# ═══════════════════════════════════════════════════════════════
# ROS2 Node
# ═══════════════════════════════════════════════════════════════
class IKBenchmarkNode(Node):
    """ROS2 node for IK benchmarking."""

    def __init__(self):
        super().__init__('ik_benchmark_node')
        self.get_logger().info("═══ ARIA IK Benchmark Node ═══")

        # Paths
        self.declare_parameter('poses_path', '')
        self.declare_parameter('config_output_path', '')

        poses_path = self.get_parameter('poses_path').value
        if not poses_path:
            from ament_index_python.packages import get_package_share_directory
            try:
                pkg = get_package_share_directory('arm_ik')
                poses_path = os.path.join(pkg, 'data', 'benchmark_poses.yaml')
            except Exception:
                poses_path = os.path.join(
                    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    'data', 'benchmark_poses.yaml'
                )

        config_path = self.get_parameter('config_output_path').value
        if not config_path:
            try:
                pkg = get_package_share_directory('arm_ik')
                config_path = os.path.join(pkg, 'config', 'selected_solver.yaml')
            except Exception:
                config_path = os.path.join(
                    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    'config', 'selected_solver.yaml'
                )

        self.poses_path = poses_path
        self.config_path = config_path

        # Service to rerun benchmark
        self.create_service(
            Trigger, '/aria/ik/benchmark', self._benchmark_cb
        )

        # Run initial benchmark
        self._run_benchmark()

    def _run_benchmark(self):
        """Generate poses if needed and run benchmark."""
        # Generate or load poses
        if os.path.exists(self.poses_path):
            self.get_logger().info(f"Loading poses from {self.poses_path}")
            poses = load_benchmark_poses(self.poses_path)
        else:
            self.get_logger().info("Generating benchmark poses...")
            poses = generate_benchmark_poses(200)
            save_benchmark_poses(poses, self.poses_path)
            self.get_logger().info(f"Saved poses to {self.poses_path}")

        # Run benchmark
        results = run_benchmark(poses)
        print_benchmark_results(results)

        # Select and save best solver
        primary, fallback = select_best_solver(results)

        config = {
            'primary_solver': primary,
            'fallback_solver': fallback,
            'benchmark_results': {
                name: {k: float(v) if isinstance(v, (float, np.floating))
                       else int(v) if isinstance(v, (int, np.integer))
                       else v
                       for k, v in metrics.items()}
                for name, metrics in results.items()
            },
        }

        os.makedirs(os.path.dirname(self.config_path), exist_ok=True)
        with open(self.config_path, 'w') as f:
            yaml.dump(config, f, default_flow_style=False)

        self.get_logger().info(f"Config saved to {self.config_path}")

    def _benchmark_cb(self, request, response):
        """Service callback to rerun benchmark."""
        try:
            self._run_benchmark()
            response.success = True
            response.message = "Benchmark complete"
        except Exception as e:
            response.success = False
            response.message = str(e)
        return response


def main(args=None):
    rclpy.init(args=args)
    node = IKBenchmarkNode()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        rclpy.shutdown()


if __name__ == "__main__":
    main()
