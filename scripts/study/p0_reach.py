#!/usr/bin/env python3
"""P0-REACH: identical-target comparison of the historical DH solver and the
URDF-faithful solver.

Targets are generated by the URDF forward kinematics from seeded random joint
configurations, so every target is reachable by construction.  Both solvers
receive the same target position and the same target pitch.  Success is decided
only by re-evaluating the returned joint angles through the URDF FK and
measuring the Cartesian error; a solver's self-reported success is ignored.

Usage:
    python3 scripts/study/p0_reach.py --n 100000
    python3 scripts/study/p0_reach.py --n 1000 --smoke
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "arm_ik" / "arm_ik" / "ik_solvers"))

from aria_study import provenance, stats  # noqa: E402
from aria_study.trial_log import TrialLog  # noqa: E402
from aria_analytical_ik import (  # noqa: E402
    JOINT_LIMITS,
    forward_kinematics,
    solve_analytical as solve_current,
)

VENDOR = ROOT / "scripts" / "study" / "vendor" / "old_ik_8d83b97.py"
SUCCESS_M = 0.005  # 5 mm, the historical benchmark's practical tolerance
STRICT_M = 0.001


def _load_old():
    spec = importlib.util.spec_from_file_location("old_ik_8d83b97", VENDOR)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


def _fk_error(q, target) -> float:
    q4 = np.asarray(q, dtype=float)[:4]
    q4 = np.clip(q4, JOINT_LIMITS[:, 0], JOINT_LIMITS[:, 1])
    p = forward_kinematics(q4)[:3, 3]
    return float(np.linalg.norm(p - target))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=100_000)
    ap.add_argument("--seed", type=int, default=20261025)
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()

    provenance.assert_clean("P0-REACH")
    old = _load_old()

    rng = np.random.default_rng(args.seed)
    q_true = rng.uniform(JOINT_LIMITS[:, 0], JOINT_LIMITS[:, 1], size=(args.n, 4))
    targets = np.array([forward_kinematics(q)[:3, 3] for q in q_true])

    fields = [
        "target_id", "solver", "target_x", "target_y", "target_z",
        "success_5mm", "success_1mm", "err_mm", "solve_ms",
        "q0", "q1", "q2", "q3",
    ]
    config = {
        "n": args.n, "seed": args.seed, "success_m": SUCCESS_M,
        "strict_m": STRICT_M, "target_pitch": 0.0,
        "target_source": "URDF FK of seeded uniform joint samples",
        "old_solver_source": "commit 8d83b97 (vendored)",
    }
    exp_id = "P0-REACH-smoke" if args.smoke else "P0-REACH"
    out = []
    t_start = datetime.now(timezone.utc)

    with TrialLog(exp_id, fields, config) as log:
        for i, (q_t, p) in enumerate(zip(q_true, targets)):
            for name, fn in (("current", solve_current), ("old_8d83b97", old.solve_analytical)):
                t0 = time.perf_counter()
                try:
                    res = fn(p, 0.0)
                    q = np.asarray(res.joint_angles, dtype=float)
                    err = _fk_error(q, p)
                except Exception:  # noqa: BLE001 - a crash is a failure, not a skip
                    q = np.full(4, np.nan)
                    err = float("inf")
                dt = (time.perf_counter() - t0) * 1000.0
                log.log({
                    "target_id": i, "solver": name,
                    "target_x": p[0], "target_y": p[1], "target_z": p[2],
                    "success_5mm": int(err <= SUCCESS_M),
                    "success_1mm": int(err <= STRICT_M),
                    "err_mm": err * 1000.0, "solve_ms": dt,
                    "q0": q[0], "q1": q[1], "q2": q[2], "q3": q[3],
                })
                out.append((name, err, dt))
            if (i + 1) % 10000 == 0:
                print(f"  {i+1}/{args.n}", flush=True)

    summary = {"exp_id": exp_id, "started_at": t_start.isoformat(),
               "finished_at": datetime.now(timezone.utc).isoformat(),
               "n": args.n, "seed": args.seed, "commit": provenance.commit()}
    for name in ("current", "old_8d83b97"):
        rows = [(e, t) for (nm, e, t) in out if nm == name]
        errs = np.array([e for e, _ in rows])
        times = np.array([t for _, t in rows])
        k5 = int(np.sum(errs <= SUCCESS_M))
        k1 = int(np.sum(errs <= STRICT_M))
        p5, lo5, hi5 = stats.wilson(k5, len(errs))
        summary[name] = {
            "recall_5mm": p5, "wilson_low": lo5, "wilson_high": hi5,
            "recall_1mm": k1 / len(errs),
            "median_err_mm": float(np.median(errs)) * 1000.0,
            "p95_err_mm": float(np.quantile(errs, 0.95)) * 1000.0,
            "median_solve_ms": float(np.median(times)),
            "p95_solve_ms": float(np.quantile(times, 0.95)),
        }
    # Paired McNemar on 5 mm success.
    cur = np.array([e <= SUCCESS_M for (nm, e, _) in out if nm == "current"], bool)
    oldv = np.array([e <= SUCCESS_M for (nm, e, _) in out if nm == "old_8d83b97"], bool)
    b = int(np.sum(cur & ~oldv))
    c = int(np.sum(~cur & oldv))
    summary["mcnemar_b_current_only"] = b
    summary["mcnemar_c_old_only"] = c
    summary["mcnemar_p"] = stats.mcnemar_exact(b, c)
    gap = summary["current"]["recall_5mm"] - summary["old_8d83b97"]["recall_5mm"]
    historical_gap = 0.99 - 0.146
    summary["recall_gap_current_minus_old"] = gap
    summary["historical_gap"] = historical_gap
    summary["fraction_of_historical_gap_explained"] = gap / historical_gap

    RAW = ROOT / "data" / "journal" / "raw"
    (RAW / f"{exp_id}_summary.json").write_text(json.dumps(summary, indent=2))
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
